"""Small ONNX Runtime inference wrapper for Raspberry Pi 4 CPU.

Observation order and normalization must match rl/environment.py. Sensor acquisition
and wheel control are intentionally hardware adapters, not tied to an Arduino.
"""
import numpy as np


class Policy:
    def __init__(self, model_path="models/ppo_trolley.onnx"):
        import onnxruntime as ort
        options = ort.SessionOptions()
        options.intra_op_num_threads = 2
        self.session = ort.InferenceSession(model_path, sess_options=options,
                                            providers=["CPUExecutionProvider"])

    def act(self, observation):
        obs = np.asarray(observation, dtype=np.float32).reshape(1, 10)
        # PPO exports a stochastic action by default. For robot control, use the
        # deterministic policy output (mean action) generated by export_model.py.
        outputs = self.session.run(None, {self.session.get_inputs()[0].name: obs})
        return np.clip(np.asarray(outputs[0]).reshape(-1)[:2], -1.0, 1.0)

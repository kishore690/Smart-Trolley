// Run after `cap add android` / `cap sync android` (the npm scripts do this for you).
// Allows cleartext HTTP ONLY to the Raspberry Pi host from VITE_API_BASE_URL, instead of
// enabling cleartext traffic for the whole app. Everything else stays HTTPS-only.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const androidDir = path.join(root, 'android');
if (!fs.existsSync(androidDir)) {
  console.error('No android/ folder yet. Run: npm run android:init');
  process.exit(1);
}

function readEnv() {
  if (process.env.VITE_API_BASE_URL) return process.env.VITE_API_BASE_URL;
  for (const f of ['.env.local', '.env']) {
    const p = path.join(root, f);
    if (!fs.existsSync(p)) continue;
    const m = fs.readFileSync(p, 'utf8').match(/^\s*VITE_API_BASE_URL\s*=\s*(.+?)\s*$/m);
    if (m) return m[1].replace(/^["']|["']$/g, '');
  }
  return '';
}

const base = readEnv();
let host = '';
try { host = new URL(base).hostname; } catch { /* handled below */ }
if (!host) {
  console.error('VITE_API_BASE_URL is missing or invalid (set it in .env). Expected e.g. http://<pi-ip>:8000');
  process.exit(1);
}

const resDir = path.join(androidDir, 'app/src/main/res/xml');
fs.mkdirSync(resDir, { recursive: true });
fs.writeFileSync(
  path.join(resDir, 'network_security_config.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/configure-android.mjs. Cleartext HTTP is allowed only for the trolley host. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">${host}</domain>
    </domain-config>
</network-security-config>
`
);

const manifestPath = path.join(androidDir, 'app/src/main/AndroidManifest.xml');
let manifest = fs.readFileSync(manifestPath, 'utf8');
if (!manifest.includes('android:networkSecurityConfig')) {
  manifest = manifest.replace('<application', '<application\n        android:networkSecurityConfig="@xml/network_security_config"');
  fs.writeFileSync(manifestPath, manifest);
}
if (!manifest.includes('android.permission.INTERNET')) {
  console.warn('Warning: INTERNET permission not found in AndroidManifest.xml (Capacitor normally adds it).');
}
console.log(`Android cleartext access limited to ${host}`);
